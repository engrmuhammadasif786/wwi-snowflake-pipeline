-- Creates Raw WWI tables in WWI_DB.RAW and defines COPY INTO statements from
-- the Azure ADLS Gen2 External Stage.
-- =============================================================================

USE WAREHOUSE WWI_WH;
USE DATABASE WWI_DB;
USE SCHEMA RAW;

CREATE TABLE IF NOT EXISTS WWI_DB.RAW.RAW_CUSTOMERS (
    CUSTOMER_ID NUMBER(38,0) NOT NULL,
    CUSTOMER_NAME VARCHAR(200) NOT NULL,
    CUSTOMER_CATEGORY_ID NUMBER(38,0) NOT NULL,
    CUSTOMER_CATEGORY_NAME VARCHAR(100) NOT NULL,
    BUYING_GROUP_NAME VARCHAR(100),
    DELIVERY_CITY_ID NUMBER(38,0),
    DELIVERY_CITY_NAME VARCHAR(100),
    STATE_PROVINCE_CODE VARCHAR(10),
    STATE_PROVINCE_NAME VARCHAR(100),
    SALES_TERRITORY VARCHAR(100),
    CREDIT_LIMIT NUMBER(18,2),
    ACCOUNT_OPENED_DATE DATE,
    STANDARD_DISCOUNT_PERCENTAGE NUMBER(18,3),
    IS_ON_CREDIT_HOLD BOOLEAN,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS WWI_DB.RAW.RAW_STOCK_ITEMS (
    STOCK_ITEM_ID NUMBER(38,0) NOT NULL,
    STOCK_ITEM_NAME VARCHAR(200) NOT NULL,
    SUPPLIER_ID NUMBER(38,0) NOT NULL,
    STOCK_GROUP_ID NUMBER(38,0) NOT NULL,
    STOCK_GROUP_NAME VARCHAR(100) NOT NULL,
    BRAND VARCHAR(100),
    SIZE VARCHAR(50),
    LEAD_TIME_DAYS NUMBER(38,0),
    IS_CHILLER_STOCK BOOLEAN,
    TAX_RATE NUMBER(18,3),
    UNIT_PRICE NUMBER(18,2),
    RECOMMENDED_RETAIL_PRICE NUMBER(18,2),
    TYPICAL_WEIGHT_PER_UNIT NUMBER(18,3),
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS WWI_DB.RAW.RAW_SUPPLIERS (
    SUPPLIER_ID NUMBER(38,0) NOT NULL,
    SUPPLIER_NAME VARCHAR(200) NOT NULL,
    SUPPLIER_CATEGORY_NAME VARCHAR(100) NOT NULL,
    DELIVERY_CITY_NAME VARCHAR(100),
    STATE_PROVINCE_CODE VARCHAR(10),
    PAYMENT_DAYS NUMBER(38,0),
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS WWI_DB.RAW.RAW_ORDERS (
    ORDER_ID NUMBER(38,0) NOT NULL,
    CUSTOMER_ID NUMBER(38,0) NOT NULL,
    SALESPERSON_PERSON_ID NUMBER(38,0),
    ORDER_DATE DATE NOT NULL,
    EXPECTED_DELIVERY_DATE DATE,
    CUSTOMER_PURCHASE_ORDER_NUMBER VARCHAR(50),
    IS_UNDERSUPPLY_BACKORDERED BOOLEAN,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
)
CLUSTER BY (TO_DATE(ORDER_DATE));

CREATE TABLE IF NOT EXISTS WWI_DB.RAW.RAW_ORDER_LINES (
    ORDER_LINE_ID NUMBER(38,0) NOT NULL,
    ORDER_ID NUMBER(38,0) NOT NULL,
    STOCK_ITEM_ID NUMBER(38,0) NOT NULL,
    DESCRIPTION VARCHAR(250),
    QUANTITY NUMBER(38,0) NOT NULL,
    UNIT_PRICE NUMBER(18,2) NOT NULL,
    TAX_RATE NUMBER(18,3) NOT NULL,
    PICKED_QUANTITY NUMBER(38,0),
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS WWI_DB.RAW.RAW_INVOICES (
    INVOICE_ID NUMBER(38,0) NOT NULL,
    CUSTOMER_ID NUMBER(38,0) NOT NULL,
    ORDER_ID NUMBER(38,0),
    DELIVERY_METHOD_ID NUMBER(38,0),
    INVOICE_DATE DATE NOT NULL,
    IS_CREDIT_NOTE BOOLEAN NOT NULL,
    TOTAL_DRY_ITEMS NUMBER(38,0),
    TOTAL_CHILLER_ITEMS NUMBER(38,0),
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
)
CLUSTER BY (TO_DATE(INVOICE_DATE), CUSTOMER_ID);

CREATE TABLE IF NOT EXISTS WWI_DB.RAW.RAW_INVOICE_LINES (
    INVOICE_LINE_ID NUMBER(38,0) NOT NULL,
    INVOICE_ID NUMBER(38,0) NOT NULL,
    STOCK_ITEM_ID NUMBER(38,0) NOT NULL,
    DESCRIPTION VARCHAR(250),
    QUANTITY NUMBER(38,0) NOT NULL,
    UNIT_PRICE NUMBER(18,2) NOT NULL,
    TAX_RATE NUMBER(18,3) NOT NULL,
    TAX_AMOUNT NUMBER(18,2) NOT NULL,
    LINE_PROFIT NUMBER(18,2) NOT NULL,
    EXTENDED_PRICE NUMBER(18,2) NOT NULL,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

