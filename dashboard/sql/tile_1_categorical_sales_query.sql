-- =============================================================================
-- Dashboard Tile 1: Categorical Distribution of WWI Sales & Profit
-- Source Mart: WWI_DB.MARTS.MART_CATEGORICAL_SALES_BY_CATEGORY
-- Clustered By: (CUSTOMER_CATEGORY_NAME, STOCK_GROUP_NAME)
-- Used by: Power BI & Looker Studio
-- =============================================================================

SELECT
    CUSTOMER_CATEGORY_NAME,
    STOCK_GROUP_NAME,
    SALES_TERRITORY,
    BUYING_GROUP_NAME,
    SUM(TOTAL_INVOICES) AS TOTAL_INVOICES,
    SUM(ACTIVE_CUSTOMERS) AS ACTIVE_CUSTOMERS,
    SUM(TOTAL_UNITS_SOLD) AS TOTAL_UNITS_SOLD,
    ROUND(SUM(TOTAL_NET_REVENUE), 2) AS TOTAL_NET_REVENUE,
    ROUND(SUM(TOTAL_GROSS_REVENUE), 2) AS TOTAL_GROSS_REVENUE,
    ROUND(SUM(TOTAL_PROFIT), 2) AS TOTAL_PROFIT,
    ROUND(
        CASE WHEN SUM(TOTAL_NET_REVENUE) > 0
            THEN (SUM(TOTAL_PROFIT) * 100.0) / SUM(TOTAL_NET_REVENUE)
            ELSE 0
        END,
        2
    ) AS PROFIT_MARGIN_PCT
FROM WWI_DB.MARTS.MART_CATEGORICAL_SALES_BY_CATEGORY
GROUP BY
    CUSTOMER_CATEGORY_NAME,
    STOCK_GROUP_NAME,
    SALES_TERRITORY,
    BUYING_GROUP_NAME
ORDER BY
    TOTAL_NET_REVENUE DESC;
